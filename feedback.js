  //  3) それ以外は、得点だけで理由を決めないことを伝える文
  function pickSummary(levels, tops) {
    if (levels.fomo === "high") {
      const matched = SUMMARY_ORDER.find((id) => levels[id] === "high");
      if (matched) return SUMMARY[matched];
    }
    return tops.length === 0 ? SUMMARY.none : SUMMARY.other;
  }

